// עבודה ברקע אחרי התשובה, בלי לעכב את התשובה לימות.
// (after() של Next המתין כאן לסיום העבודה לפני שליחת התשובה - וזה גרם לניתוקים.)
// העבודה ממשיכה כל עוד המופע של השרת חי; אם הוא נעצר באמצע - היא תושלם בפעם הבאה שתידרש.
export function bg(fn) {
  setTimeout(() => {
    Promise.resolve()
      .then(fn)
      .catch((e) => console.error('רקע:', String(e?.message || e).slice(0, 200)));
  }, 0);
}
