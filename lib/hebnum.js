function plainToken(tok) {
  if (NQ_PLAIN[tok]) return NQ_PLAIN[tok];
  const m = tok.match(/^ו[\u05B0-\u05C7]+(.+)$/); // ו' החיבור
  if (m && NQ_PLAIN[m[1]]) return 'ו' + NQ_PLAIN[m[1]];
  const px = tok.match(/^([ובכלמהש]{1,2})([^\u05B0-\u05C7].*)$/); // אות שימוש בלי ניקוד לפני מספר (ו-2,500)
  if (px) return px[1] + plainToken(px[2]);
  return tok.replace(/[\u0591-\u05C7]/g, '');
}
// כמו speakable, אבל המילים שנוספו - בלי ניקוד ובכתיב מלא
export function speakablePlain(text) {
  return speakable(expandAbbrev(text)).replace(/[^\s,.!?;:]+/g, (w) => (/[\u0591-\u05C7]/.test(w) ? plainToken(w) : w));
}

