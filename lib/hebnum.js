export function speakable(text) {
  let s = String(text || '').replace(/[‐-–]/g, '-')
    .replace(/\(\s*-?\d+(?:\.\d+)?\s*°\s*F\s*\)/g, '') // פרנהייט בסוגריים - מיותר בטלפון
    .replace(/(\d)\s*°\s*F/g, '$1 מעלות פרנהייט');
  // שעה: 10:30 -> עשר ושלושים
  s = s.replace(/(^|[^\d:])([01]?\d|2[0-3]):([0-5]\d)(?![\d:])/g, (_, pre, h, m) =>
    `${pre}${numberWords(Number(h))}${Number(m) ? ' ' + (m === '30' ? 'וָחֵצִי' : m === '15' ? 'וָרֶבַע' : vav(numberWords(Number(m)))) : ''}`);
  // סימנים אחרי מספר
  s = s.replace(/(\d)\s*°\s*C?/g, '$1 מַעֲלוֹת').replace(/(\d)\s*%/g, '$1 אָחוּז').replace(/(\d)\s*₪/g, '$1 שְׁקָלִים')
    .replace(/₪\s*(\d[\d,.]*)/g, '$1 שְׁקָלִים').replace(/\$\s*(\d[\d,.]*)/g, '$1 דּוֹלָר').replace(/(\d)\s*\$/g, '$1 דּוֹלָר');
  // מספר (עם פסיקים של אלפים / נקודה עשרונית), אולי עם אות שימוש ומקף לפניו (ב-22)
  s = s.replace(/(^|[^\dא-ת.,])(?:([ובכלמהש])-?)?(-)?(\d{1,3}(?:,\d{3})+|\d+)(?:\.(\d+))?(?=(\s*)([^\s\d]*))/g,
    (all, pre, prefix = '', minus, int, frac, _sp, next) => {
      // "2 ילדים" -> שְׁנֵי ילדים, "2 שנים" -> שְׁתֵּי שנים
      if (int === '2' && !frac && /^[א-ת]/.test(next || '') && !/^(אחוז|מעלות|נקודה)/.test(next)) {
        return pre + prefix + (genderOf(next) === 'm' ? 'שְׁנֵי' : 'שְׁתֵּי');
      }
      const digits = int.replace(/,/g, '');
      // מספר טלפון / קוד ארוך בלי פסיקים - ספרה ספרה
      if (!int.includes(',') && digits.length >= 7) return pre + prefix + digits.split('').map((d) => F[Number(d)]).join(' ');
      const n = Number(digits);
      const isYear = !frac && digits.length === 4 && n >= 1900 && n <= 2100;
      const g = isYear ? 'f' : genderOf(next);
      let w = numberWords(n, frac ? 'f' : g);
      if (frac) w += ' נְקוּדָה ' + (frac.length <= 2 ? numberWords(Number(frac)) : frac.split('').map((d) => F[Number(d)]).join(' '));
      return pre + prefix + (minus && !prefix ? 'מִינוּס ' : '') + w;
    });
  for (const [re, to] of WORD_FIX) s = s.replace(re, to);
  return s;
}
