// ו' החיבור: וּ לפני שווא ולפני ב/מ/פ, וַ לפני חטף פתח, וְ בשאר המקרים
function vav(word) {
  const first = word[0];
  const marks = word.slice(1, 4);
  if ('במפ'.includes(first) || /^[^ְ-ׇ][ּׁׂ]*ְ/.test(word)) return 'וּ' + word;
  if (/ֲ/.test(marks.slice(0, 2))) return 'וַ' + word;
  return 'וְ' + word;
}

// חלקים של מספר מתחת לאלף
function below1000(n, g) {
  const parts = [];
  const h = Math.floor(n / 100), r = n % 100;
  if (h) parts.push(HUND[h]);
  if (r >= 11 && r <= 19) parts.push((g === 'm' ? M_TEEN : F_TEEN)[r - 10]);
  else {
    const t = Math.floor(r / 10), u = r % 10;
    if (r === 10) parts.push((g === 'm' ? M : F)[10]);
    else {
      if (t) parts.push(TENS[t]);
      if (u) parts.push((g === 'm' ? M : F)[u]);
    }
  }
  return parts;
}

export function numberWords(n, g = 'f') {
  n = Math.floor(Math.abs(n));
  if (n === 0) return F[0];
  if (n >= 1e12) return String(n).split('').map((d) => F[Number(d)]).join(' ');
  const parts = [];
  const bil = Math.floor(n / 1e9), mil = Math.floor((n % 1e9) / 1e6), th = Math.floor((n % 1e6) / 1000), rest = n % 1000;
  if (bil) parts.push(bil === 1 ? 'מִילְיַארְד' : bil === 2 ? 'שְׁנֵי מִילְיַארְד' : `${joinParts(below1000(bil, 'm'))} מִילְיַארְד`);
  if (mil) parts.push(mil === 1 ? 'מִילְיוֹן' : mil === 2 ? 'שְׁנֵי מִילְיוֹן' : `${joinParts(below1000(mil, 'm'))} מִילְיוֹן`);
  if (th) parts.push(th <= 10 ? THOUS[th] : `${joinParts(below1000(th, 'm'))} אֶלֶף`);
  parts.push(...below1000(rest, g));
  return joinParts(parts);
}
function joinParts(parts) {
  parts = parts.filter(Boolean);
  if (parts.length > 1) parts[parts.length - 1] = vav(parts[parts.length - 1]);
  return parts.join(' ');
}

// מין דקדוקי לפי המילה שאחרי המספר: רוב המילים שנגמרות ב-ים זכר (שקלים, ימים, אחוזים)
const FEM_IM = /^(שנים|ביצים|ערים|מילים|שעורים|יונים|נמלים|רחלים)$/;
const MASC = /^(אחוז|אחוזים|שקל|שקלים|דולר|דולרים|יורו|ק"מ|קילומטר|קילו|גרם|ליטר|מטר|ס"מ|ילד|ילדים|אנשים|ימים|חודשים|תלמידים|מיליון|אלף)$/;
function genderOf(next) {
  const w = String(next || '').replace(/^[ובכלמהש]{1}(?=..)/, '').replace(/[^א-ת"]/g, '');
  const raw = String(next || '').replace(/[^א-ת"]/g, '');
  if (MASC.test(raw) || MASC.test(w)) return 'm';
  if (/ים$/.test(raw) && !FEM_IM.test(raw)) return 'm';
  return 'f';
}

